import os
import struct
import math
from typing import List, Tuple
import numpy as np


def write_binary_stl(filename: str, triangles: List[Tuple[Tuple[float, float, float], Tuple[float, float, float], Tuple[float, float, float]]]) -> None:
    """
    Write a list of 3D triangles to a standard binary STL file without external dependencies.
    triangles: List of ((v1x, v1y, v1z), (v2x, v2y, v2z), (v3x, v3y, v3z))
    """
    os.makedirs(os.path.dirname(os.path.abspath(filename)), exist_ok=True)
    num_triangles = len(triangles)
    
    with open(filename, "wb") as f:
        # 80-byte header
        header_text = f"Binary STL Generated by CT Simulation Framework ({num_triangles} facets)"
        header = header_text.encode("ascii")[:80].ljust(80, b"\0")
        f.write(header)
        
        # 4-byte unsigned int: triangle count
        f.write(struct.pack("<I", num_triangles))
        
        # Triangle records: 50 bytes each
        for v1, v2, v3 in triangles:
            # Calculate surface normal vector using cross product
            u = (v2[0] - v1[0], v2[1] - v1[1], v2[2] - v1[2])
            v = (v3[0] - v1[0], v3[1] - v1[1], v3[2] - v1[2])
            nx = u[1] * v[2] - u[2] * v[1]
            ny = u[2] * v[0] - u[0] * v[2]
            nz = u[0] * v[1] - u[1] * v[0]
            norm = math.sqrt(nx * nx + ny * ny + nz * nz)
            if norm > 1e-9:
                nx, ny, nz = nx / norm, ny / norm, nz / norm
            else:
                nx, ny, nz = 0.0, 0.0, 0.0
                
            record = struct.pack(
                "<12fH",
                nx, ny, nz,
                v1[0], v1[1], v1[2],
                v2[0], v2[1], v2[2],
                v3[0], v3[1], v3[2],
                0
            )
            f.write(record)


def create_cylinder_triangles(
    radius: float,
    height: float,
    center: Tuple[float, float, float] = (0.0, 0.0, 0.0),
    segments: int = 48
) -> List[Tuple[Tuple[float, float, float], Tuple[float, float, float], Tuple[float, float, float]]]:
    # Generate 3D triangle mesh facets for a closed cylinder.
    cx, cy, cz = center
    z_bottom = cz - height / 2.0
    z_top = cz + height / 2.0
    
    angles = [2.0 * math.pi * i / segments for i in range(segments)]
    bottom_ring = [(cx + radius * math.cos(a), cy + radius * math.sin(a), z_bottom) for a in angles]
    top_ring = [(cx + radius * math.cos(a), cy + radius * math.sin(a), z_top) for a in angles]
    
    triangles = []
    
    # Side walls
    for i in range(segments):
        next_i = (i + 1) % segments
        b1, b2 = bottom_ring[i], bottom_ring[next_i]
        t1, t2 = top_ring[i], top_ring[next_i]
        
        triangles.append((b1, b2, t1))
        triangles.append((b2, t2, t1))
        
    # Bottom cap (wound clockwise from below)
    b_center = (cx, cy, z_bottom)
    for i in range(segments):
        next_i = (i + 1) % segments
        triangles.append((b_center, bottom_ring[next_i], bottom_ring[i]))
        
    # Top cap (wound counter-clockwise from above)
    t_center = (cx, cy, z_top)
    for i in range(segments):
        next_i = (i + 1) % segments
        triangles.append((t_center, top_ring[i], top_ring[next_i]))
        
    return triangles


def create_box_triangles(
    size_x: float,
    size_y: float,
    size_z: float,
    center: Tuple[float, float, float] = (0.0, 0.0, 0.0)
) -> List[Tuple[Tuple[float, float, float], Tuple[float, float, float], Tuple[float, float, float]]]:
    # Generate 3D triangle mesh facets for an axis-aligned rectangular prism/box.
    cx, cy, cz = center
    dx, dy, dz = size_x / 2.0, size_y / 2.0, size_z / 2.0
    
    # 8 corners
    v = [
        (cx - dx, cy - dy, cz - dz),  # 0
        (cx + dx, cy - dy, cz - dz),  # 1
        (cx + dx, cy + dy, cz - dz),  # 2
        (cx - dx, cy + dy, cz - dz),  # 3
        (cx - dx, cy - dy, cz + dz),  # 4
        (cx + dx, cy - dy, cz + dz),  # 5
        (cx + dx, cy + dy, cz + dz),  # 6
        (cx - dx, cy + dy, cz + dz),  # 7
    ]
    
    # 12 triangles (2 per face)
    faces = [
        # bottom
        (v[0], v[2], v[1]), (v[0], v[3], v[2]),
        # top
        (v[4], v[5], v[6]), (v[4], v[6], v[7]),
        # front
        (v[0], v[1], v[5]), (v[0], v[5], v[4]),
        # back
        (v[2], v[3], v[7]), (v[2], v[7], v[6]),
        # left
        (v[0], v[4], v[7]), (v[0], v[7], v[3]),
        # right
        (v[1], v[2], v[6]), (v[1], v[6], v[5])
    ]
    return faces


def create_sphere_triangles(
    radius: float,
    center: Tuple[float, float, float] = (0.0, 0.0, 0.0),
    lat_segments: int = 24,
    lon_segments: int = 36
) -> List[Tuple[Tuple[float, float, float], Tuple[float, float, float], Tuple[float, float, float]]]:
    """Generate 3D triangle mesh facets for a closed, watertight UV sphere."""
    cx, cy, cz = center
    triangles = []
    
    grid = []
    for i in range(lat_segments + 1):
        phi = -math.pi / 2.0 + math.pi * i / lat_segments
        ring = []
        for j in range(lon_segments):
            theta = 2.0 * math.pi * j / lon_segments
            x = cx + radius * math.cos(phi) * math.cos(theta)
            y = cy + radius * math.cos(phi) * math.sin(theta)
            z = cz + radius * math.sin(phi)
            ring.append((x, y, z))
        grid.append(ring)
        
    for i in range(lat_segments):
        for j in range(lon_segments):
            next_j = (j + 1) % lon_segments
            v_bl = grid[i][j]
            v_br = grid[i][next_j]
            v_tl = grid[i + 1][j]
            v_tr = grid[i + 1][next_j]
            
            if i > 0:
                triangles.append((v_bl, v_br, v_tl))
            if i < lat_segments - 1:
                triangles.append((v_br, v_tr, v_tl))
                
    return triangles


def generate_benchmark_multi_material_phantom(target_dir: str = "sample_stls") -> dict:
    """
    Generate spatially co-registered multi-material assemblies:
    Assembly 1: Cylindrical PMMA matrix with Cu, Al, and Ti rods
    Assembly 2: Cubic Acrylic Container with Embedded Dense Metal Sphere Core
    """
    os.makedirs(target_dir, exist_ok=True)
    
    # 1. Outer Cylinder Matrix (PMMA)
    matrix_triangles = create_cylinder_triangles(radius=20.0, height=30.0, center=(0.0, 0.0, 0.0))
    matrix_path = os.path.join(target_dir, "matrix_cylinder.stl")
    write_binary_stl(matrix_path, matrix_triangles)
    
    # 2. Other Cykinders with more dense materials
    cu_triangles = create_cylinder_triangles(radius=3.5, height=28.0, center=(10.0, 0.0, 0.0))
    cu_path = os.path.join(target_dir, "insert_copper_rod.stl")
    write_binary_stl(cu_path, cu_triangles)
    
    al_triangles = create_cylinder_triangles(radius=3.5, height=28.0, center=(-10.0, 0.0, 0.0))
    al_path = os.path.join(target_dir, "insert_aluminium_rod.stl")
    write_binary_stl(al_path, al_triangles)
    
    ti_triangles = create_cylinder_triangles(radius=2.5, height=28.0, center=(0.0, 10.0, 0.0))
    ti_path = os.path.join(target_dir, "insert_titanium_core.stl")
    write_binary_stl(ti_path, ti_triangles)
    
    # 3. Cube with Sphere Core (Assembly 2)
    cube_triangles = create_box_triangles(size_x=24.0, size_y=24.0, size_z=24.0, center=(0.0, 0.0, 0.0))
    cube_path = os.path.join(target_dir, "outer_cube_matrix.stl")
    write_binary_stl(cube_path, cube_triangles)
    
    # Embedded Central Sphere (dense sphere)
    sphere_triangles = create_sphere_triangles(radius=6.0, center=(0.0, 0.0, 0.0))
    sphere_path = os.path.join(target_dir, "inner_sphere_core.stl")
    write_binary_stl(sphere_path, sphere_triangles)

    # Embedded Off-Center Defect Sphere(feels like a satellite rotating around main sphere) (e.g. Copper or Air void at +6mm, +6mm)
    satellite_triangles = create_sphere_triangles(radius=3.0, center=(6.0, 6.0, 0.0))
    satellite_path = os.path.join(target_dir, "satellite_sphere_defect.stl")
    write_binary_stl(satellite_path, satellite_triangles)

    generated = {
        "matrix_cylinder": matrix_path,
        "insert_copper": cu_path,
        "insert_aluminium": al_path,
        "insert_titanium": ti_path,
        "outer_cube_matrix": cube_path,
        "inner_sphere_core": sphere_path,
        "satellite_sphere_defect": satellite_path
    }
    
    print(f"[PhantomGenerator] Generated {len(generated)} aligned STL files in: {target_dir}")
    for name, p in generated.items():
        print(f"  - {name}: {p} ({os.path.getsize(p)} bytes)")
        
    return generated


if __name__ == "__main__":
    generate_benchmark_multi_material_phantom()
